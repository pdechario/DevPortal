/**
 * Builds a greeting for the given name.
 *
 * Exists to give the library a real, typed export so the package compiles and
 * emits declarations. Replace it with something useful.
 *
 * @param name - Who to greet.
 * @returns The greeting.
 */
export function greet(name: string): string {
  return `Hello, ${name}!`;
}
